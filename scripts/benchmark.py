#!/usr/bin/env python3
"""Run the benchmark (docs/BENCHMARK.md explains it).

    python scripts/benchmark.py              print the tables
    python scripts/benchmark.py --write      also write benchmark/results.json and refresh the tables in docs/BENCHMARK.md
    python scripts/benchmark.py --check      exit 1 if results.json or the docs table is out of date
    python scripts/benchmark.py --draft-labels   (re)write benchmark/labels.yaml from the simple oracle, for the owner to review

Offline: it only reads the frozen snapshots in tests/sample/snapshot and benchmark/snapshot.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import yaml  # noqa: E402

from depscan import bench  # noqa: E402

DOC = ROOT / "docs" / "BENCHMARK.md"
RESULTS = ROOT / "benchmark" / "results.json"
START, END = "<!-- BENCHMARK:START (generated by scripts/benchmark.py --write: do not edit by hand) -->", "<!-- BENCHMARK:END -->"

LABEL_HEADER = """# Benchmark labels for the fixtures that are not hand-labelled.
#
# !!! NEEDS MANUAL VERIFICATION !!!
# Written by `python scripts/benchmark.py --draft-labels`, NOT by the project owner. For each pinned version it lists the
# advisories (grouped by alias, lowest CVE id as the name) that `depscan.bench.oracle_affected` says affect it. That oracle is
# a second, deliberately simple reading of the OSV range rules over the frozen advisory text, not an independent source of
# truth: it can share a misreading of an advisory with depscan. Everything not listed is treated as NOT affected.
# Check each entry against the advisory (https://osv.dev/vulnerability/<id>), edit this file if you disagree, then set
# `verified_by_owner: true`. Until then every benchmark number is provisional.
verified_by_owner: false
"""


def build_doc(res: dict) -> str:
    text = DOC.read_text("utf-8")
    block = f"{START}\n\n{bench.render_tables(res)}\n\n{END}"
    return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--draft-labels", action="store_true")
    args = ap.parse_args()
    if args.draft_labels:
        labels = {"fixtures": bench.draft_labels(bench.load_fixtures())}
        (ROOT / "benchmark" / "labels.yaml").write_text(LABEL_HEADER + yaml.safe_dump(labels, sort_keys=True, width=140), "utf-8")
        print("wrote benchmark/labels.yaml (a DRAFT: verified_by_owner is false)")
        return 0
    res = bench.run_all()
    text = json.dumps(res, indent=1, sort_keys=True) + "\n"
    if args.check:
        stale = [n for n, ok in [("benchmark/results.json", RESULTS.exists() and RESULTS.read_text("utf-8") == text),
                                 ("docs/BENCHMARK.md", DOC.exists() and DOC.read_text("utf-8") == build_doc(res))] if not ok]
        print("up to date" if not stale else f"out of date: {', '.join(stale)} (run with --write)")
        return 1 if stale else 0
    print(bench.render_tables(res))
    print(f"\nlabels verified by owner: {res['labels_verified_by_owner']}")
    if args.write:
        RESULTS.write_text(text, "utf-8")
        DOC.write_text(build_doc(res), "utf-8")
        print(f"wrote {RESULTS.relative_to(ROOT)} and refreshed the tables in {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
